#!/usr/bin/env python3
"""Genera l'icona di MIMUS (packaging/AppIcon.png e AppIcon.icns, serve Pillow):
un Gallimimus stilizzato in pixel art 8 bit su fondo bianco."""
import io, os, struct
from PIL import Image, ImageDraw, ImageFilter

# Gallimimus che corre verso destra (X = pixel)
DINO = """
...............................XXXX.....
..............................XXXXXXX...
..............................X.XXXXXXXX
..............................XXXXXX....
...............................XXXX.....
...............................XXX......
..............................XXXX......
..............................XXX.......
.............................XXXX.......
.............................XXX........
............................XXXX........
...........................XXXXX........
.........................XXXXXX.........
..................XXXXXXXXXXXXX.........
XX.........XXXXXXXXXXXXXXXXXXXX.........
.XXXX...XXXXXXXXXXXXXXXXXXXXXXX.........
...XXXXXXXXXXXXXXXXXXXXXXXXXXXXXX.......
......XXXXXXXXXXXXXXXXXXXXXXXX..XX......
..........XXXXXXXXXXXXXXXXXXXX....X.....
..............XXXXXXXXXXXXXXX...........
...............XXXXXXXXXXXXX............
................XXXXX...XXXXX...........
...............XXXX......XXXX...........
..............XXX.........XXX...........
.............XXX..........XXX...........
............XXX............XX...........
...........XXX.............XX...........
..........XXX..............XX...........
.........XXX...............XXX..........
........XXXX...............XXXXX........
"""

S = 1024
INK = (29, 29, 31, 255)

def icon():
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    # ombra leggera per staccare il bianco da sfondi chiari
    sh = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(sh).rounded_rectangle((100, 116, 924, 940), 185, fill=(0, 0, 0, 70))
    img.alpha_composite(sh.filter(ImageFilter.GaussianBlur(16)))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((100, 100, 924, 924), 185, fill=(255, 255, 255, 255), outline=(222, 222, 226, 255), width=3)
    rows = [r for r in DINO.strip("\n").split("\n")]
    w, h = max(len(r) for r in rows), len(rows)
    px = 16                                   # lato di un "pixel"
    ox = (S - w * px) // 2
    oy = (S - (h + 2) * px) // 2 + 10
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "X":
                d.rectangle((ox + x * px, oy + y * px, ox + (x + 1) * px - 1, oy + (y + 1) * px - 1), fill=INK)
    # terreno tratteggiato, come nei giochi a 8 bit
    gy = oy + (h + 1) * px
    for x in range(0, w, 3):
        d.rectangle((ox + x * px, gy, ox + (x + 2) * px - 1, gy + px // 2 - 1), fill=(29, 29, 31, 110))
    return img

def icns(base):
    chunks = b""
    for typ, size in ((b"ic07", 128), (b"ic08", 256), (b"ic09", 512), (b"ic10", 1024)):
        buf = io.BytesIO()
        base.resize((size, size), Image.NEAREST if size >= 512 else Image.LANCZOS).save(buf, "PNG")
        data = buf.getvalue()
        chunks += typ + struct.pack(">I", len(data) + 8) + data
    return b"icns" + struct.pack(">I", len(chunks) + 8) + chunks

here = os.path.dirname(os.path.abspath(__file__))
im = icon()
im.save(os.path.join(here, "AppIcon.png"))
open(os.path.join(here, "AppIcon.icns"), "wb").write(icns(im))
print("ok")
